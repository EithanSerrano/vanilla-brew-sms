function pdfHeader(pdoc, gs = false) {
  pdoc.setFillColor(...(gs ? [70, 70, 70] : [97, 64, 51]));
  pdoc.rect(0, 0, 210, 24, 'F');
  pdoc.setTextColor(255, 255, 255);
  pdoc.setFontSize(15);
  pdoc.setFont('helvetica', 'bold');
  pdoc.text('vanilla brew', 14, 10);
  pdoc.setFontSize(7.5);
  pdoc.setFont('helvetica', 'normal');
  pdoc.text('SHOP MANAGEMENT SYSTEM', 14, 18);
  pdoc.setTextColor(0, 0, 0);
}

function pdfMeta(pdoc, { docType, docId, generatedBy, generatedAt, dateFrom, dateTo }, gs = false) {
  const dateRange = !dateTo || dateFrom === dateTo
    ? fmtDateStr(dateFrom)
    : `${fmtDateStr(dateFrom)} – ${fmtDateStr(dateTo)}`;
  const labelFill = gs ? [215, 215, 215] : [245, 242, 240];

  autoTable(pdoc, {
    startY: 28,
    body: [
      [
        { content: 'Document Type', styles: { fontStyle: 'bold', fillColor: labelFill } },
        docType,
        { content: 'Generated By', styles: { fontStyle: 'bold', fillColor: labelFill } },
        generatedBy,
      ],
      [
        { content: 'Document ID', styles: { fontStyle: 'bold', fillColor: labelFill } },
        docId,
        { content: 'Date & Time', styles: { fontStyle: 'bold', fillColor: labelFill } },
        generatedAt,
      ],
      [
        { content: 'Date Coverage', styles: { fontStyle: 'bold', fillColor: labelFill } },
        { content: dateRange, colSpan: 3 },
      ],
    ],
    theme: 'grid',
    styles: { fontSize: 7.5, cellPadding: 2, textColor: [50, 50, 50] },
    columnStyles: { 0: { cellWidth: 38 }, 1: { cellWidth: 57 }, 2: { cellWidth: 38 }, 3: { cellWidth: 57 } },
    tableWidth: 190,
    margin: { left: 10, right: 10 },
  });
}

function pdfSeparator(pdoc) {
  const y = pdoc.lastAutoTable.finalY + 3;
  pdoc.setDrawColor(180, 180, 180);
  pdoc.setLineWidth(0.3);
  pdoc.line(10, y, 200, y);
  return y + 3;
}

function pdfSectionTitle(pdoc, title, y, gs = false, x = 10) {
  pdoc.setFontSize(9);
  pdoc.setFont('helvetica', 'bold');
  pdoc.setTextColor(...(gs ? [80, 80, 80] : [97, 64, 51]));
  pdoc.text(title, x, y);
  pdoc.setTextColor(0, 0, 0);
}

