function splitTimestamp(ts) {
  if (!ts) return { date: '—', time: '—', raw: null };
  const d = ts.toDate ? ts.toDate() : new Date(ts);
  if (isNaN(d.getTime())) return { date: '—', time: '—', raw: null };
  return {
    date: d.toLocaleDateString('en-US'),
    time: d.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: true }),
    raw: d,
  };
}

function fmtDateStr(str) {
  if (!str) return '—';
  const d = new Date(str + 'T00:00:00');
  return isNaN(d.getTime()) ? str : d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
}

async function generateNextDocId(typeCode, dateStr) {
  const d = new Date(dateStr + 'T00:00:00');
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  const yy = String(d.getFullYear()).slice(-2);
  const prefix = `D${typeCode}${mm}${dd}${yy}`;
  const fsnap = await getDocs(collection(db, 'generateddocuments'));
  const nums = fsnap.docs
    .map(dc => (dc.data().documentId || ''))
    .filter(id => id.startsWith(prefix))
    .map(id => parseInt(id.slice(prefix.length)) || 0);
  return `${prefix}${String((nums.length ? Math.max(...nums) : 0) + 1).padStart(3, '0')}`;
}

